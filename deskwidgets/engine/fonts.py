"""Text fonts. Widgets ask for "DW Light", "DW Semibold" ... and for the bundled icon font.

Cairo's toy font API only knows normal and bold, so every weight is a family name of its own:
* Linux: a generated fontconfig file maps each "DW <weight>" alias to the user's font with
  the right weight. It must be in place before Cairo touches fontconfig for the first time.
* Windows: each alias maps to a Segoe UI family (or the chosen font); the icon font is
  registered for this process only.
"""
import ctypes
import os
import shutil
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape

import cairo

from ..core import paths
from ..core.util import log, write_atomic

WEIGHTS = {'Light': 'light', 'Regular': 'regular', 'Medium': 'medium', 'Semibold': 'semibold',
           'Bold': 'bold', 'Heavy': 'extrabold'}
ICON_FAMILY = 'Material Design Icons'
DEFAULT_LINUX_FONT = 'Ubuntu Sans'
SYSTEM_FONT_WINDOWS = 'Segoe UI'


class FontMap:
    """Translates the font names widgets use into what Cairo can select, and reports the system's CJK font."""

    def __init__(self, family='auto', windows=None):
        self.windows = sys.platform == 'win32' if windows is None else windows
        self.family = family or 'auto'
        self._cjk = None

    def face(self, name, weight):
        """(family, cairo weight) for a font name from a widget."""
        if not self.windows or not name.startswith('DW '):
            return name, weight
        alias = name[3:]
        custom = self.family != 'auto'
        base = self.family if custom else SYSTEM_FONT_WINDOWS
        if alias == 'Light':
            return base if custom else 'Segoe UI Light', cairo.FONT_WEIGHT_NORMAL
        if alias == 'Semibold':
            return (base, cairo.FONT_WEIGHT_BOLD) if custom else ('Segoe UI Semibold', cairo.FONT_WEIGHT_NORMAL)
        if alias == 'Bold':
            return base, cairo.FONT_WEIGHT_BOLD
        if alias == 'Heavy':
            return (base, cairo.FONT_WEIGHT_BOLD) if custom else ('Segoe UI Black', cairo.FONT_WEIGHT_NORMAL)
        return base, cairo.FONT_WEIGHT_NORMAL

    @property
    def cjk(self):
        """Family of a font with Japanese glyphs (anime widgets), or '' when the system has none."""
        if self._cjk is None:
            self._cjk = _find_cjk(self.windows)
        return self._cjk


def setup(settings):
    """Prepares fonts for this process and returns the FontMap. Call it before the first drawing."""
    family = settings.get('font') or 'auto'
    if sys.platform == 'win32':
        _register_windows_font(paths.FONTS / 'MaterialDesignIcons.ttf')
    else:
        os.environ['FONTCONFIG_FILE'] = str(write_fontconf(family))
        _reload_fontconfig()
    return FontMap(family)


def write_fontconf(family='auto', path=None):
    """The fontconfig file used by every widget. Paths are absolute: fontconfig resolves a
    relative FONTCONFIG_FILE against /etc/fonts, not the working directory."""
    family = escape(DEFAULT_LINUX_FONT if family in ('', 'auto') else family)
    aliases = '\n'.join(
        f'  <match target="pattern"><test name="family"><string>DW {alias}</string></test>'
        f'<edit name="family" mode="assign" binding="strong"><string>{family}</string></edit>'
        f'<edit name="family" mode="append" binding="weak"><string>sans-serif</string></edit>'
        f'<edit name="weight" mode="assign" binding="strong"><const>{weight}</const></edit></match>'
        for alias, weight in WEIGHTS.items())
    text = f'''<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- generated by deskwidgets: the DeskWidgets text aliases + the bundled icon font -->
<fontconfig>
  <include ignore_missing="yes">{escape(_system_fontconf())}</include>
  <dir>{escape(str(paths.FONTS))}</dir>
  <match target="font">
    <edit name="rgba" mode="assign"><const>none</const></edit>
    <edit name="antialias" mode="assign"><bool>true</bool></edit>
    <edit name="hintstyle" mode="assign"><const>hintslight</const></edit>
  </match>
{aliases}
</fontconfig>
'''
    path = path or paths.RUN / 'fonts.conf'
    write_atomic(path, text)
    return path


def _system_fontconf():
    """The distribution's own fontconfig file. Looked up on disk: asking libfontconfig would
    initialise it before our FONTCONFIG_FILE is in place."""
    candidates = [Path(os.environ.get('FONTCONFIG_PATH', '/etc/fonts')) / 'fonts.conf',
                  Path('/usr/local/etc/fonts/fonts.conf'), Path('/run/current-system/sw/etc/fonts/fonts.conf'),
                  Path('/opt/homebrew/etc/fonts/fonts.conf')]
    return str(next((c for c in candidates if c.is_file()), candidates[0]))


def _reload_fontconfig():
    """If something initialised fontconfig before us, make it read the file we just pointed it to."""
    try:
        lib = ctypes.CDLL('libfontconfig.so.1')
        lib.FcInitReload.restype = ctypes.c_int
        lib.FcInitReload()
    except (OSError, AttributeError):
        pass


def _register_windows_font(path):
    FR_PRIVATE = 0x10
    if not ctypes.windll.gdi32.AddFontResourceExW(str(path), FR_PRIVATE, 0):
        log(f'cannot register the icon font {path}')


def _find_cjk(windows):
    if windows:
        return 'Yu Gothic UI'
    if shutil.which('fc-match'):
        try:
            out = subprocess.run(['fc-match', '-f', '%{family[0]}', ':lang=ja'], capture_output=True, text=True,
                                 timeout=10).stdout.strip()
            probe = subprocess.run(['fc-list', ':lang=ja', 'family'], capture_output=True, text=True,
                                   timeout=10).stdout.strip()
            return out if probe else ''
        except (OSError, subprocess.SubprocessError):
            pass
    return ''

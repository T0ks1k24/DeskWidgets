"""Talking to conky: the font config, the environment of a widget process, previews."""
import hashlib
import os
import subprocess
from xml.sax.saxutils import escape

from . import paths
from .catalog import option_values, resolved_accent
from .util import log, write_atomic

# alias to fontconfig weight. Widgets ask for "DW Light", "DW Semibold" etc. cairo's toy font API
# only knows normal/bold, so each weight gets its own family name.
WEIGHTS = {'Light': 'light', 'Regular': 'regular', 'Medium': 'medium', 'Semibold': 'semibold',
           'Bold': 'bold', 'Heavy': 'extrabold'}


def write_fontconf(settings, path=None):
    """Font config used by every widget process. Uses absolute paths: fontconfig resolves a
    relative FONTCONFIG_FILE against /etc/fonts, not the working directory."""
    family = escape(settings.get('font') or 'Ubuntu Sans')
    aliases = '\n'.join(
        f'  <match target="pattern"><test name="family"><string>DW {alias}</string></test>'
        f'<edit name="family" mode="assign" binding="strong"><string>{family}</string></edit>'
        f'<edit name="family" mode="append" binding="weak"><string>sans-serif</string></edit>'
        f'<edit name="weight" mode="assign" binding="strong"><const>{weight}</const></edit></match>'
        for alias, weight in WEIGHTS.items())
    text = f'''<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- generated by deskwidgets — DeskWidgets text aliases + the bundled icon font -->
<fontconfig>
  <include ignore_missing="yes">/etc/fonts/fonts.conf</include>
  <dir>{escape(os.path.abspath(paths.FONTS))}</dir>
  <match target="font">
    <edit name="rgba" mode="assign"><const>none</const></edit>
    <edit name="antialias" mode="assign"><bool>true</bool></edit>
    <edit name="hintstyle" mode="assign"><const>hintslight</const></edit>
  </match>
{aliases}
</fontconfig>
'''
    path = path or paths.FONTCONF
    os.makedirs(os.path.dirname(path), exist_ok=True)
    write_atomic(path, text)
    return path


def image_png(src, max_side=1024):
    """Cache any image as a PNG in RUN/img (cairo in conky only reads PNG)."""
    if not src or not os.path.isfile(os.path.expanduser(src)):
        return ''
    src = os.path.expanduser(src)
    key = hashlib.sha1(f'{src}:{os.path.getmtime(src)}:{max_side}'.encode()).hexdigest()[:16]
    out = os.path.join(paths.RUN, 'img', key + '.png')
    if os.path.exists(out):
        return out
    os.makedirs(os.path.dirname(out), exist_ok=True)
    try:
        import gi
        gi.require_version('GdkPixbuf', '2.0')
        from gi.repository import GdkPixbuf
        pix = GdkPixbuf.Pixbuf.new_from_file(src)
        pix = pix.apply_embedded_orientation() or pix
        w, h = pix.get_width(), pix.get_height()
        k = min(1.0, max_side / max(w, h))
        if k < 1:
            pix = pix.scale_simple(max(1, round(w * k)), max(1, round(h * k)), GdkPixbuf.InterpType.HYPER)
        pix.savev(out + '.tmp', 'png', [], [])
        os.replace(out + '.tmp', out)
        return out
    except Exception as e:   # unreadable or unsupported image
        log(f'image {src}: {e}')
        return ''


def write_options(inst, t, directory=None, lang=None):
    """RUN/opts/<id>: the instance options as key=value lines for lib.lua (L.OPT).
    File options also get <key>_png, a PNG copy the widget can draw."""
    values = option_values(inst, t, lang)
    for o in t.options:
        if o.type == 'file':
            values[o.key + '_png'] = image_png(values.get(o.key))
    lines = []
    for key, value in values.items():
        if isinstance(value, bool):
            value = '1' if value else '0'
        elif isinstance(value, (list, tuple)):
            value = ','.join(map(str, value))
        value = str(value).replace('\\', '\\\\').replace('\r', '').replace('\n', '\\n')
        lines.append(f'{key}={value}')
    directory = directory or os.path.join(paths.RUN, 'opts')
    os.makedirs(directory, exist_ok=True)
    path = os.path.join(directory, inst['id'])
    write_atomic(path, '\n'.join(lines) + '\n')
    return path


def widget_env(inst, t, *, lang, scale, size_px, pos=(0, 0), opts_path=None, interval=None):
    w, h = size_px
    return {
        'MAC_ID': inst['id'], 'MAC_TYPE': t.id, 'MAC_SIZE': inst['size'], 'MAC_STYLE': inst['style'],
        'MAC_ACCENT': resolved_accent(inst, t), 'MAC_LANG': lang, 'MAC_SCALE': f'{scale:g}',
        'MAC_W': str(w), 'MAC_H': str(h), 'MAC_X': str(pos[0]), 'MAC_Y': str(pos[1]),
        'MAC_INTERVAL': f'{interval if interval is not None else t.interval_for(option_values(inst, t)):g}',
        'MAC_OPTS': opts_path or '', 'MAC_ENGINE': paths.ENGINE, 'MAC_WIDGET_DIR': t.dir,
        'MAC_RUN': paths.RUN, 'MAC_CONFIG': paths.CONFIG, 'MAC_BIN': paths.bin_path(),
        'FONTCONFIG_FILE': paths.FONTCONF,
    }


def render(t, out, *, size=None, style=None, accent=None, lang='uk', scale=1.0, options=None, demo=True,
           wait=True, settings=None):
    """Renders one frame of a widget to a PNG (gallery thumbnails, `deskwidgets preview`)."""
    from .grid import Grid
    size = size or t.size
    inst = {'id': f'preview-{t.id}', 'type': t.id, 'size': size, 'style': style or t.style,
            'accent': accent or t.accent, 'options': options or {}}
    if settings is not None and not os.path.exists(paths.FONTCONF):
        write_fontconf(settings)
    grid = Grid(1920, 1080, {'scale': scale, 'gap': 16, 'margin_side': 24, 'margin_top': 44, 'margin_bottom': 88})
    opts = write_options(inst, t, directory=os.path.join(paths.RUN, 'preview-opts'), lang=lang)
    env = dict(os.environ)
    env.update(widget_env(inst, t, lang=lang, scale=scale, size_px=grid.window_px(size), opts_path=opts, interval=0.8))
    env['MAC_PREVIEW'] = out
    if demo:
        env['MAC_DEMO'] = '1'
    proc = subprocess.Popen(['conky', '-c', paths.CONF], env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if not wait:
        return proc
    try:
        proc.wait(timeout=30)
    except subprocess.TimeoutExpired:
        proc.kill()
    return os.path.exists(out)
